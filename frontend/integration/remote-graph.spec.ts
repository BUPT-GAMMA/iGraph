import { readFileSync, writeFileSync } from 'node:fs';
import { test, expect } from '@playwright/test';

function required(name: string) {
  const value = process.env[name];
  if (!value) throw new Error(`Live acceptance requires ${name}`);
  return value;
}

test('real connection form, refreshed selection, model query evidence and disconnect', async ({ page, request }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  const uid = required('IGRAPH_E2E_USER_ID');
  expect(uid.startsWith('remote-graph-test-')).toBeTruthy();
  const manifest = JSON.parse(readFileSync(required('IGRAPH_TEST_CORA_MANIFEST'), 'utf8'));
  const headers: Record<string, string> = { 'X-User-ID': uid };
  if (process.env.IGRAPH_E2E_AUTHORIZATION) headers.Authorization = process.env.IGRAPH_E2E_AUTHORIZATION;
  await page.setExtraHTTPHeaders(headers);
  await page.addInitScript(id => { localStorage.setItem('igraph_user_id', id); if (!localStorage.getItem('igraph-language')) localStorage.setItem('igraph-language', 'en'); }, uid);
  const created = await request.post('/api/sessions', { headers, data: { model: required('IGRAPH_TEST_MODEL_ID'), initial_message_preview: 'Remote graph browser acceptance' } });
  expect(created.ok()).toBeTruthy();
  const session = await created.json();
  const name = `Cora browser ${Date.now()}`;
  await page.goto(`/?session=${encodeURIComponent(session.session_id)}`);
  await page.getByRole('button', { name: 'Remote databases', exact: true }).click();
  await expect(page.getByLabel('Name', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/connections-list.png` });
  await page.getByRole('button', { name: 'New connection', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('URI', { exact: true }).fill(process.env.IGRAPH_TEST_NEO4J_APP_URI || required('IGRAPH_TEST_NEO4J_URI'));
  await page.getByLabel('Database', { exact: true }).fill(required('IGRAPH_TEST_NEO4J_DATABASE'));
  await page.getByLabel('Username', { exact: true }).fill(required('IGRAPH_TEST_NEO4J_READER_USER'));
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/connection-form.png` });
  await page.getByLabel('Password', { exact: true }).fill(required('IGRAPH_TEST_NEO4J_READER_PASSWORD'));
  await page.getByRole('button', { name: 'Test connection', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Connection usable.' })).toBeVisible({ timeout: 40_000 });
  const beforeSave = await request.get('/api/remote-graphs', { headers });
  expect((await beforeSave.json()).connections.some((c: { name: string }) => c.name === name)).toBeFalsy();
  let bindingFailures = 0;
  await page.route('**/api/sessions/*/remote-graph', async route => {
    if (route.request().method() === 'PUT' && bindingFailures === 0) {
      bindingFailures += 1;
      await route.abort('failed');
    } else await route.continue();
  });
  await page.getByRole('button', { name: 'Save and use', exact: true }).click();
  await expect(page.getByText(/Saved, not in use/)).toBeVisible();
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('');
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/saved-not-used.png` });
  const savedOnce = (await (await request.get('/api/remote-graphs', { headers })).json()).connections.filter((c: { name: string }) => c.name === name);
  expect(savedOnce).toHaveLength(1);
  await page.getByRole('button', { name: 'Retry use', exact: true }).click();
  await expect(page.getByText('Selected', { exact: true })).toBeVisible();
  const afterRetry = (await (await request.get('/api/remote-graphs', { headers })).json()).connections.filter((c: { name: string }) => c.name === name);
  expect(afterRetry).toHaveLength(1);
  expect(afterRetry[0].connection_id).toBe(savedOnce[0].connection_id);
  writeFileSync(`${required('IGRAPH_TEST_EVIDENCE_DIR')}/browser-binding-retry.json`, JSON.stringify({ session_id: session.session_id, connection_id: savedOnce[0].connection_id, count_before_retry: savedOnce.length, count_after_retry: afterRetry.length, transport_failures: bindingFailures }));
  await page.unroute('**/api/sessions/*/remote-graph');
  await page.getByRole('button', { name: `Edit ${name}`, exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'Save and use', exact: true }).click();
  await expect(page.getByText('Selected', { exact: true })).toBeVisible({ timeout: 40_000 });
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/connection-selected.png` });
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.reload();
  await expect(page.getByText(`Remote: ${name} · ${required('IGRAPH_TEST_NEO4J_DATABASE')}`, { exact: true })).toBeVisible();
  const collapseWorkspace = page.getByRole('button', { name: 'Collapse right sidebar', exact: true });
  if (await collapseWorkspace.isVisible()) await collapseWorkspace.click();
  await page.locator('textarea').fill('请实际查询选中的远程数据库总节点数，并报告结果和来源。');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  const evidence = page.getByRole('region', { name: 'Remote query evidence' });
  await expect(evidence.first()).toBeVisible({ timeout: 180_000 });
  await expect(evidence.filter({ hasText: String(manifest.node_count) }).first()).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeVisible({ timeout: 180_000 });
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/query-collapsed.png` });
  const details = evidence.filter({ hasText: String(manifest.node_count) }).first().locator('details');
  await expect(details).not.toHaveAttribute('open', '');
  await details.locator('summary').focus();
  await page.keyboard.press('Enter');
  await expect(details).toHaveAttribute('open', '');
  await expect(details.locator('pre').first()).toBeVisible();
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/query-expanded.png` });
  await page.reload();
  await expect(page.getByRole('region', { name: 'Remote query evidence' }).filter({ hasText: String(manifest.node_count) }).first()).toBeVisible();
  await page.locator('textarea').fill('继续重新查询远程 Paper 的 label 聚合，并导出查询工具生成的原始 JSON 结果文件；不要手工抄录。然后在工作区读取该文件计算计数之和。请返回 node_count 并说明文件。');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Stop current task', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Send', exact: true })).toBeVisible({ timeout: 180_000 });
  const messagesResponse = await request.get(`/api/sessions/${session.session_id}/messages`, { headers });
  const messages = (await messagesResponse.json()).messages;
  const answer = messages.filter((m: { role: string }) => m.role === 'assistant').at(-1);
  expect(answer.content.replace(/,/g, '')).toContain(String(manifest.node_count));
  expect(answer.tools.some((t: { tool: string }) => t.tool === 'workspace_bash')).toBeTruthy();
  expect(answer.tools.some((t: { tool: string; result: unknown }) => t.tool === 'query_remote_graph' && JSON.stringify(t.result).includes('artifact_path'))).toBeTruthy();
  await testInfo.attach('followup-tools', { body: JSON.stringify(answer), contentType: 'application/json' });
  const record = JSON.stringify({ session_id: session.session_id, connection_name: name, expected_node_count: manifest.node_count, answer });
  expect(record.includes(required('IGRAPH_TEST_NEO4J_READER_PASSWORD'))).toBeFalsy();
  writeFileSync(`${required('IGRAPH_TEST_EVIDENCE_DIR')}/browser-session.json`, record);
  await testInfo.attach('session', { body: JSON.stringify({ session_id: session.session_id, connection_name: name, expected_node_count: manifest.node_count }), contentType: 'application/json' });
  await page.getByRole('button', { name: 'Remote databases', exact: true }).click();
  await page.getByRole('button', { name: 'Disconnect from conversation', exact: true }).click();
  await expect(page.getByText('Selected', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: `Delete ${name}`, exact: true }).click();
  await expect(page.getByRole('button', { name: `Use ${name}`, exact: true })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'New connection', exact: true }).click();
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/connection-mobile-en.png` });
  await page.getByRole('button', { name: 'Save and use', exact: true }).scrollIntoViewIfNeeded();
  await expect(page.getByRole('button', { name: 'Save and use', exact: true })).toBeInViewport();
  await page.evaluate(() => localStorage.setItem('igraph-language', 'zh'));
  await page.reload();
  await page.getByRole('button', { name: '远程数据库', exact: true }).click();
  await page.getByRole('button', { name: '新建连接', exact: true }).click();
  await page.screenshot({ path: `${required('IGRAPH_TEST_EVIDENCE_DIR')}/connection-mobile-zh.png` });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
});
